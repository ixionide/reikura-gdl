use anyhow::bail;
use reikura_util::{const_iota, encoding::sjis_to_utf8};

use crate::{
    AssetName, Vm,
    instruction::{InstructionInfo, Value},
};

const_iota! {
    u8 = iota,
    END,
    COLOR,
    SHUTDOWN,
    CLEAR,
    NAME,
    _5,
    BREAK,
    _7,
    READ,
}

const TAG: u8 = 17;
const VOICE: u8 = 19;
const MESSAGE: u8 = 255;

const_iota! {
    u8 = iota,
    TEXT,
    SHADOW,
    OUTLINE,
}

pub fn pm(vm: &mut Vm, info: InstructionInfo) -> anyhow::Result<()> {
    let window: u8 = vm.parser.read_param()?;

    'param: loop {
        match vm.parser.read_param()? {
            END => {
                if let Some(0) = vm.parser.peek_opcode() {
                    vm.parser.state.ip += 1;
                };

                break 'param;
            }
            COLOR => {
                let color: u8 = vm.parser.read_param()?;
                let [r, g, b] = vm.parser.read_param::<[u8; _]>()?;

                match color {
                    TEXT => (),
                    SHADOW => (),
                    OUTLINE => (),
                    _ => bail!("unknown color: {color}"),
                }
            }
            SHUTDOWN => {
                // exit with message
                vm.state.exit();
            }
            CLEAR => {}
            NAME => {
                let name_id: u8 = vm.parser.read_param()?;
            }
            BREAK => {}
            READ => {
                let msg_index: Value = vm.parser.read_param()?;

                if let Some(save) = &mut vm.save {
                    let index = msg_index.evaluate(&vm.ctx).try_into()?;
                    save.set_message_read(index);
                } else {
                    bail!("no save manager");
                }
            }
            TAG => {
                let name_id: Value = vm.parser.read_param()?;
            }
            VOICE => {
                let name: AssetName = vm.parser.read_param()?;
                let voice = vm.assets.load_voice(name)?;

                vm.audio.voice = Some(voice);
                vm.audio.play_voice(None)?;
            }
            MESSAGE => {
                // capacity might be a bit bigger than needed, but its far better than realloc
                let mut msg_buffer = Vec::with_capacity(info.param_len - 1);

                'msg: loop {
                    match vm.parser.read_param::<u8>()? {
                        0 => break 'msg,
                        index @ 1..0x7F => {
                            msg_buffer.extend(CHARSET[index as usize]);
                        }
                        0x7F => {
                            let byte: u8 = vm.parser.read_param()?;
                            msg_buffer.push(byte);
                        }
                        byte @ 0x80.. => {
                            msg_buffer.push(byte);
                            let byte: u8 = vm.parser.read_param()?;
                            msg_buffer.push(byte);
                        }
                    };
                }

                let message = sjis_to_utf8(&msg_buffer)?;
            }

            cmd => bail!("unknown cmd: {cmd}"),
        }
    }

    Ok(())
}

